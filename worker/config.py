IN_PROGRESS = DATA / "in_progress"
DONE = DATA / "done"
FAILED = DATA / "failed"
ARTIFACTS = DATA / "artifacts"
AUDIO = DATA / "audio"          # постоянное хранилище аудио (не удаляем — решение пользователя)

DATABASE_URL = os.environ["DATABASE_URL"]

OPENROUTER_API_KEY = os.environ["OPENROUTER_API_KEY"]
ELEVENLABS_API_KEY = os.environ["ELEVENLABS_API_KEY"]

DRAFT_MODEL = os.environ.get("DRAFT_MODEL", "openai/whisper-large-v3-turbo")
# Язык черновика НЕ фиксируем: речь бывает двуязычной (ru+en в одной фразе), а жёсткий
# язык калечит вторую половину. Текст черновика мы всё равно не используем — из него
# берётся только карта речи (границы + no_speech_prob/logprob). Что whisper местами
# уезжает в перевод — на границы речи не влияет, а галлюцинации ловит speechmap.
# Задать язык принудительно можно через env, если запись заведомо моноязычная.
DRAFT_LANGUAGE = os.environ.get("DRAFT_LANGUAGE", "")
JUDGE_MODEL = os.environ.get("JUDGE_MODEL", "google/gemini-2.5-flash-lite")
SCRIBE_MODEL = os.environ.get("SCRIBE_MODEL", "scribe_v2")

DAILY_BUDGET_USD = float(os.environ.get("DAILY_BUDGET_USD", "2.0"))

# Время начала записи Plaud отдаёт в UTC — проверено на ночных записях: у записи с
# start_at 09-02 22:51 облако ставит в название «09-03», и с поправкой +4 это 02:51
# ночи, что сходится с одиннадцатичасовой длительностью. Названия же облако делает
# по МЕСТНОМУ времени, поэтому для человекочитаемых имён и транскриптов держим зону.
LOCAL_TZ = os.environ.get("LOCAL_TZ", "Asia/Dubai")

# Синхронизация с облаком Plaud: токены создаёт `plaud login` на хосте, в контейнер
# файл монтируется. Публичного API нет — ходим тем же путём, что официальный CLI.
PLAUD_TOKENS = os.environ.get("PLAUD_TOKENS", "/plaud/tokens.json")
PLAUD_SYNC_ENABLED = os.environ.get("PLAUD_SYNC", "1") == "1"
PLAUD_SYNC_EVERY_SEC = int(os.environ.get("PLAUD_SYNC_EVERY_SEC", "900"))   # раз в 15 минут

# Пулы обработчиков — по одному на этап, а не общий на всё. Этапы упираются в
# РАЗНЫЕ ресурсы: скачивание и транскрипция ждут чужие сервисы (Plaud, ElevenLabs),
# детектор и опознание жгут локальный процессор. Общий пул означал, что три
# тяжёлых детектора занимают все слоты, пока сеть простаивает.
# Этапы связаны только артефактами на диске, поэтому пулы работают независимо.
# Роль контейнера: all | download | detect | quality | resolve. Этапы разнесены по
# отдельным контейнерам, чтобы правка кода одного не обрывала работу остальных.
WORKER_ROLE = os.environ.get("WORKER_ROLE", "all")
# Сколько ждать завершения начатых этапов при остановке (детектор длинной записи
# считает минутами, обрывать его на полуслове — терять эту работу целиком).
STOP_GRACE_SEC = int(os.environ.get("STOP_GRACE_SEC", "900"))

DOWNLOAD_WORKERS = int(os.environ.get("DOWNLOAD_WORKERS", "6"))
DETECT_WORKERS = int(os.environ.get("DETECT_WORKERS", "5"))    # CPU: VAD + классификатор
# Одновременные запросы к Scribe ограничены тарифом ElevenLabs (на Starter немного).
# Упёршийся в лимит запрос не теряется: клиент ретраит его с бэкоффом.
QUALITY_WORKERS = int(os.environ.get("QUALITY_WORKERS", "6"))
RESOLVE_WORKERS = int(os.environ.get("RESOLVE_WORKERS", "5"))  # CPU: эмбеддинги голоса

# Локальные этапы работают с пониженным приоритетом: машина у пользователя рабочая,
# и конвейер не должен драться с ней за процессор. Уступчивый поток забирает только
# то, что никому не нужно, поэтому их можно держать больше, чем ядер.
WORKER_NICE = int(os.environ.get("WORKER_NICE", "15"))
# По потоку на модель: при десятке параллельных обработчиков многопоточный ONNX
# отнимает больше на переключениях, чем выигрывает. Нам важна пропускная
# способность конвейера, а не скорость одной записи.
ONNX_THREADS = int(os.environ.get("ONNX_THREADS", "1"))

EMBED_MODEL = os.environ.get("EMBED_MODEL", "/models/campplus_zh_en_advanced.onnx")



# Детектор речи (локальный, бесплатный): Silero VAD + классификатор аудио-событий.
# Заменил платный whisper-черновик: на 11-часовой ночной записи whisper пометил бы
# речью 86% длительности, VAD+CED дают 2.6% — и это подтверждается прослушиванием.
VAD_MODEL = os.environ.get("VAD_MODEL", "/models/silero_vad.onnx")
VAD_THRESHOLD = 0.5
VAD_MIN_SILENCE = 0.8         # пауза, после которой кусок речи считается законченным
VAD_MIN_SPEECH = 0.25
TAG_MODEL = os.environ.get("TAG_MODEL", "/models/sherpa-onnx-ced-tiny-audio-tagging-2024-04-19")
TAG_SPEECH_MIN = 0.35         # ниже — классификатор считает кусок не речью (шум, ТВ, тишина)
REGION_MERGE_GAP_SEC = 8.0    # склеиваем речевые регионы через паузы короче этого
REGION_PAD_SEC = 4.0          # поля региона — чтобы не срезать начало/конец фразы

# Качественный проход: файл длиннее — режем на куски (лимиты API по размеру запроса)
QUALITY_CHUNK_SEC = 1200.0    # 20 мин на запрос к Scribe
QUALITY_MIN_CHUNK_SEC = 0.6   # короче не отправляем: в таком куске нет ни слова,
                              # а API отвергает его как битый файл
SCRIBE_PRICE_PER_HOUR = 0.22

# Диаризация/опознание
UTTER_GAP_SEC = 0.8           # пауза внутри реплики одного speaker_id
MIN_EMBED_SEC = 1.5           # короче — эмбеддинг не считаем, спикер наследуется
EMBED_CLIP_MAX_SEC = 45.0
CLUSTER_JOIN = 0.70           # склейка центроидов (усреднённые векторы, косинус высокий)
# Кластеризация ИДЁТ ПО РЕПЛИКАМ, метки провайдера — только подсказка: он умеет
# слепить двух людей в одну метку, и тогда её центроид не соответствует никому.
ANCHOR_MIN_SEC = 3.0          # опора кластеризации: короче — вектор слишком шумный
# Порог склейки ОДИНОЧНЫХ реплик: у одного человека они сходятся около 0.5, а не
# 0.7 (усреднения-то нет). Подобран по записи #19, где Scribe слепил двух людей:
# на 0.45 Матвей и Владимир слипаются, на 0.65 один человек рассыпается надвое,
# а на 0.50-0.55 разделение чистое — берём середину плато.
UTTER_JOIN = 0.60                 # запасной, когда база пуста и подбирать не по чему
# Насколько близко короткая реплика должна звучать к кластеру, чтобы попасть в него.
# Без порога она приписывалась к ближайшему всегда — и кластеры собирали чужие
# голоса с похожестью 0.26, склеивая нескольких людей в одного.
ATTACH_MIN_COS = 0.45
# Диапазон автоподбора порога под конкретную запись (см. _pick_join)
JOIN_MIN, JOIN_MAX, JOIN_STEP = 0.50, 0.70, 0.025
CLUSTER_MIN_SEC = 15.0        # метка короче — не образует свой кластер, а липнет к ближайшему
CONF_OK = 0.70                # ниже — ambiguous
TOP2_MARGIN = 0.15            # отрыв top1-top2 меньше — ambiguous
# Переназначение отдельной реплики из её кластера к другому человеку: только когда
# голос говорит об этом уверенно (иначе доверяем кластеру, он усреднён и надёжнее).
REASSIGN_MIN_COS = 0.65       # насколько близко к новому кандидату
REASSIGN_MIN_GAP = 0.20       # и насколько он дальше отрывается от дефолта кластера

# Детектор смены говорящего ВНУТРИ реплики: Scribe иногда не замечает перехват и
# склеивает двух людей в один speaker_id. Ищем точку разреза по границам слов
# (эмбеддинг считаем по склеенной речи, без пауз — см. AudioCache.embed_spans).
SPLIT_MIN_SEC = 8.0           # реплики короче не трогаем: мало данных для двух половин
SPLIT_MIN_SIDE_SEC = 2.5      # каждая половина должна содержать столько речи
SPLIT_MAX_COS = 0.60          # косинус половин ниже — считаем, что говорят разные люди
SPLIT_MAX_DEPTH = 2           # рекурсия: максимум 4 части из одной реплики

# Классификатор аудио-событий — самая дорогая часть детектора. Короткие всплески
# ему не по зубам (доверяем VAD), длинным достаточно пробы с начала куска.
TAG_MIN_DUR = float(os.environ.get("TAG_MIN_DUR", "0.8"))
TAG_PROBE_SEC = float(os.environ.get("TAG_PROBE_SEC", "6.0"))
